func testModel(t *testing.T) *Model {
	t.Helper()
	data, err := os.ReadFile("../../fixtures/hosts/sample.hosts")
	if err != nil {
		t.Fatal(err)
	}
	return NewModel(string(data), nil)
}

func TestModel_EditUndoRedoFindAndReplace(t *testing.T) {
	model := testModel(t)
	tester := ui.NewTester(model.View, 1100, 720)
	original := model.Editor.Buffer.String()
	model.Editor.Select(0, 0)
	model.Editor.Insert("# inserted\n")
	if !strings.HasPrefix(model.Editor.Buffer.String(), "# inserted\n") {
		t.Fatal("insert did not update the buffer")
	}
	model.Editor.Run(editor.Undo)
	if got := model.Editor.Buffer.String(); got != original {
		t.Fatalf("undo = %q", got)
	}
	model.Editor.Run(editor.Redo)
	if !strings.HasPrefix(model.Editor.Buffer.String(), "# inserted\n") {
		t.Fatal("redo did not restore the edit")
	}
	model.Editor.Run(editor.Undo)

	model.Editor.Find("broken.test")
	tester.Frame()
	if count, current := model.Editor.FindMatches(); count != 1 || current != 0 {
		t.Fatalf("find matches = %d, %d", count, current)
	}
	model.Editor.Run(editor.FindReplace)
	tester.Frame()
	if model.findBar == nil {
		t.Fatal("find bar was not rendered")
	}
	*model.findBar.Query() = "broken.test"
	*model.findBar.Replacement() = "fixed.test"
	tester.Frame()
	model.findBar.ReplaceAll()
	if strings.Contains(model.Editor.Buffer.String(), "broken.test") || !strings.Contains(model.Editor.Buffer.String(), "fixed.test") {
		t.Fatalf("replace all result:\n%s", model.Editor.Buffer.String())
	}
}

func TestModel_LargeHostsGoToAndScroll(t *testing.T) {
	var generated bytes.Buffer
	if err := hostsfixture.Generate(&generated, 100000); err != nil {
		t.Fatal(err)
	}
	model := NewModel(generated.String(), nil)
	tester := ui.NewTester(model.View, 1100, 720)
	model.Editor.GoTo(editor.Pos{Line: 99999})
	model.Editor.ScrollTo(99999)
	tester.Frame()
	if got := model.Editor.CursorPos().Line; got != 99999 {
		t.Fatalf("cursor line = %d", got)
	}
	first, last := model.Editor.VisibleLines()
	if first < 90000 || last != 100000 {
		t.Fatalf("visible lines = %d..%d", first, last)
	}
	model.Editor.Find("host-099999.phase0.test")
	tester.Frame()
	if count, _ := model.Editor.FindMatches(); count != 1 {
		t.Fatalf("large text find count = %d", count)
	}
}

func TestModel_HiddenWindowRetainsEditorState(t *testing.T) {
	model := testModel(t)
	tester := ui.NewTester(model.View, 1100, 720)
	model.Editor.Select(10, 25)
	model.Editor.SetScrollY(40)
	tester.Frame()
	buffer := model.Editor.Buffer
	selections := model.Editor.Selections()
	scroll := model.Editor.ScrollY()
	tester.SetWindowHidden(true)
	tester.SetWindowHidden(false)
	tester.Frame()
	if model.Editor.Buffer != buffer {
		t.Fatal("hidden window replaced the editor buffer")
	}
	if got := model.Editor.Selections(); len(got) != len(selections) || got[0] != selections[0] {
		t.Fatalf("selections = %+v, want %+v", got, selections)
	}
	if got := model.Editor.ScrollY(); got != scroll {
		t.Fatalf("scroll = %v, want %v", got, scroll)
	}
}

