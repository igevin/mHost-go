package desktop

import (
	"bytes"
	"context"
	"fmt"

	"github.com/egoist/mygo/ui"
	"github.com/egoist/mygo/ui/editor"
	"github.com/igevin/mHost-go/internal/hostsfixture"
)

type DNSManager interface {
	Start(context.Context) error
	Stop(context.Context) error
	Running() bool
	Errors() <-chan error
}

type Model struct {
	Selected            string
	Editor              *editor.State
	DNS                 DNSManager
	DNSServiceAvailable bool
	DialogOpen          bool
	DNSStatus           string
	EditorNotice        string
	OnDNSStart          func()
	OnDNSStop           func()

	findBar           *editor.FindBar
	diagnosticVersion uint64
}

func NewModel(text string, dns DNSManager) *Model {
	buffer := editor.NewBuffer(text)
	buffer.SetLanguage(HostsLanguage())
	return &Model{
		Selected: "editor",
		Editor: &editor.State{
			Buffer:         buffer,
			Label:          "Hosts editor",
			KeepScrollbars: true,
		},
		DNS:                 dns,
		DNSServiceAvailable: true,
		DNSStatus:           "DNS test is stopped",
		diagnosticVersion:   ^uint64(0),
	}
}

func (m *Model) View(c *ui.Context) {
	m.Editor.RenderFindBar = func(c *ui.Context, bar ui.Element, find *editor.FindBar) {
		m.findBar = find
		editor.DefaultFindBar(c, bar, find)
	}
	m.updateDiagnostics()
	ui.Row(c).Fill().AlignItems(ui.Stretch).Children(func() {
		ui.Sidebar(c, &m.Selected, func() {
			ui.SidebarItem(c, "editor", nil, "Hosts Editor")
			ui.SidebarItem(c, "dns", nil, "DNS Lab")
			ui.SidebarItem(c, "settings", nil, "Settings Placeholder")
		}).Width(220)
		ui.Column(c).Grow(1).FillHeight().Children(func() {
			switch m.Selected {
			case "dns":
				m.dnsView(c)
			case "settings":
				ui.Column(c).Grow(1).Center().Gap(8).Children(func() {
					ui.Text(c, "Settings Placeholder").FontSize(22).Bold()
					ui.Text(c, "No preference is persisted in this Phase 0 prototype.")
				})
			default:
				m.editorView(c)
			}
		})
	})
	ui.AlertDialog(c, &m.DialogOpen, "Phase 0", "Technical validation only. No changes are written to Hosts profiles.", "Close")
}

func (m *Model) editorView(c *ui.Context) {
	theme := c.Theme()
	ui.Row(c).Gap(12).Padding(10, 14).AlignItems(ui.Center).BorderWidth(0, 0, 1, 0).BorderColor(theme.Border).Children(func() {
		ui.Column(c).Grow(1).Gap(3).Children(func() {
			ui.Text(c, "Hosts editor").FontSize(20).Bold()
			ui.Text(c, "In-memory synthetic data · Cmd-F find · Cmd-Option-F replace · Ctrl-G go to line").FontSize(11).TextColor(theme.TextMuted)
		})
		if ui.Button(c, "Load 100k").Clicked() {
			var generated bytes.Buffer
			if err := hostsfixture.Generate(&generated, 100000); err != nil {
				m.EditorNotice = "Generate large sample: " + err.Error()
			} else {
				m.Editor.Buffer.Reset(generated.String())
				m.EditorNotice = "Loaded 100,000 synthetic lines"
			}
		}
		if ui.Button(c, "About Phase 0").Clicked() {
			m.DialogOpen = true
		}
	})
	editor.View(c, m.Editor).Grow(1).FillWidth().AutoFocus()
	position := m.Editor.CursorPos()
	ui.Row(c).Gap(16).Padding(6, 14).BorderWidth(1, 0, 0, 0).BorderColor(theme.Border).Children(func() {
		ui.Text(c, fmt.Sprintf("Ln %d, Col %d", position.Line+1, position.Col+1)).FontSize(12).TextColor(theme.TextMuted)
		ui.Text(c, fmt.Sprintf("%d lines", m.Editor.Buffer.LineCount())).FontSize(12).TextColor(theme.TextMuted)
		ui.Text(c, fmt.Sprintf("%d diagnostics", len(m.Editor.Diagnostics()))).FontSize(12).TextColor(theme.TextMuted)
		if m.EditorNotice != "" {
			ui.Text(c, m.EditorNotice).FontSize(12).TextColor(theme.TextMuted)
		}
		ui.Spacer(c)
		ui.Text(c, "Close hides to tray; Quit restores DNS").FontSize(12).TextColor(theme.TextMuted)
	})
}

func (m *Model) dnsView(c *ui.Context) {
	theme := c.Theme()
	ui.Column(c).Fill().Padding(28).Gap(16).Children(func() {
		ui.Text(c, "DNS lifecycle lab").FontSize(24).Bold()
		ui.Text(c, "Explicit test only: 127.0.0.1:53 → 127.0.0.1:1053").TextColor(theme.TextMuted)
		ui.Text(c, "Use a dedicated Mac. Starting requires administrator authorization and temporarily changes the active service DNS.").TextColor(theme.TextMuted)
		ui.Text(c, m.DNSStatus).FontSize(14)
		ui.Row(c).Gap(10).Children(func() {
			if ui.PrimaryButton(c, "Start DNS Test").Disabled(m.DNS == nil || !m.DNSServiceAvailable || m.DNS.Running()).Clicked() && m.OnDNSStart != nil {
				m.OnDNSStart()
			}
			if ui.Button(c, "Stop DNS Test").Disabled(m.DNS == nil || !m.DNSServiceAvailable || !m.DNS.Running()).Clicked() && m.OnDNSStop != nil {
				m.OnDNSStop()
			}
		})
		ui.Text(c, "phase0.test resolves to 192.0.2.53 while the test is active.").FontSize(12).TextColor(theme.TextMuted)
	})
}

func (m *Model) updateDiagnostics() {
	version := m.Editor.Buffer.Version()
	if version == m.diagnosticVersion {
		return
	}
	m.Editor.SetDiagnostics(version, HostsDiagnostics(m.Editor.Buffer))
	m.diagnosticVersion = version
}
